-- -----------------------------------------------------------------------------
-- 1. inventory_balance (센터×SKU 재고 잔량)
-- -----------------------------------------------------------------------------
CREATE TABLE wms.inventory_balance (
    inventory_balance_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    center_info_id        BIGINT        NOT NULL,
    item_info_id          BIGINT        NOT NULL,
    qty_on_hand           NUMERIC(12,0) NOT NULL,
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by            VARCHAR(50)   NOT NULL,
    updated_by            VARCHAR(50)   NOT NULL,
    CONSTRAINT inventory_balance_pk PRIMARY KEY (inventory_balance_id),
    CONSTRAINT inventory_balance_ux1 UNIQUE (center_info_id, item_info_id),
    CONSTRAINT inventory_balance_center_info_fk FOREIGN KEY (center_info_id)
        REFERENCES wms.center_info (center_info_id),
    CONSTRAINT inventory_balance_item_info_fk FOREIGN KEY (item_info_id)
        REFERENCES wms.item_info (item_info_id),
    CONSTRAINT inventory_balance_ck1 CHECK (qty_on_hand >= 0)
);

CREATE INDEX inventory_balance_ix1 ON wms.inventory_balance (item_info_id);

COMMENT ON TABLE  wms.inventory_balance                      IS '센터×SKU 재고 잔량';
COMMENT ON COLUMN wms.inventory_balance.inventory_balance_id IS '재고 잔량 대리키';
COMMENT ON COLUMN wms.inventory_balance.center_info_id       IS '센터 대리키 (FK → center_info)';
COMMENT ON COLUMN wms.inventory_balance.item_info_id         IS '상품 대리키 (FK → item_info)';
COMMENT ON COLUMN wms.inventory_balance.qty_on_hand          IS '가용 재고 수량 (≥ 0)';
COMMENT ON COLUMN wms.inventory_balance.created_at           IS '등록 일시';
COMMENT ON COLUMN wms.inventory_balance.updated_at           IS '수정 일시';
COMMENT ON COLUMN wms.inventory_balance.created_by           IS '등록자';
COMMENT ON COLUMN wms.inventory_balance.updated_by           IS '수정자';

-- -----------------------------------------------------------------------------
-- 2. inventory_history (재고 증감 이력)
-- -----------------------------------------------------------------------------
CREATE TABLE wms.inventory_history (
    inventory_history_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    inventory_balance_id  BIGINT        NOT NULL,
    txn_type_code         VARCHAR(20)   NOT NULL,
    change_qty            NUMERIC(12,0) NOT NULL,
    after_qty             NUMERIC(12,0) NOT NULL,
    order_kind            VARCHAR(20),
    order_no              VARCHAR(50),
    line_no               INT,
    changed_by            VARCHAR(50)   NOT NULL,
    changed_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by            VARCHAR(50)   NOT NULL,
    updated_by            VARCHAR(50)   NOT NULL,
    CONSTRAINT inventory_history_pk PRIMARY KEY (inventory_history_id),
    CONSTRAINT inventory_history_inventory_balance_fk FOREIGN KEY (inventory_balance_id)
        REFERENCES wms.inventory_balance (inventory_balance_id),
    CONSTRAINT inventory_history_ck1 CHECK (after_qty >= 0)
);

CREATE INDEX inventory_history_ix1 ON wms.inventory_history (inventory_balance_id, changed_at);
CREATE INDEX inventory_history_ix2 ON wms.inventory_history (order_kind, order_no, changed_at);
CREATE INDEX inventory_history_ix3 ON wms.inventory_history (changed_at);

COMMENT ON TABLE  wms.inventory_history                      IS '재고 증감 이력';
COMMENT ON COLUMN wms.inventory_history.inventory_history_id IS '재고 이력 대리키';
COMMENT ON COLUMN wms.inventory_history.inventory_balance_id IS '재고 잔량 대리키 (FK → inventory_balance)';
COMMENT ON COLUMN wms.inventory_history.txn_type_code        IS '재고 거래 유형 코드 (코드그룹: INV_TXN_TYPE, 예: INBOUND 입고반영, OUTBOUND 출고반영, INIT 초기재고)';
COMMENT ON COLUMN wms.inventory_history.change_qty           IS '변동 수량 (입고·INIT +, 출고 −)';
COMMENT ON COLUMN wms.inventory_history.after_qty            IS '반영 후 가용 잔량 (≥ 0)';
COMMENT ON COLUMN wms.inventory_history.order_kind           IS '참조 주문 종류 (코드그룹: ORDER_KIND, 예: INBOUND, OUTBOUND). INIT는 NULL. 물리 FK 없음';
COMMENT ON COLUMN wms.inventory_history.order_no             IS '참조 주문번호. INIT는 NULL. 물리 FK 없음(입·출고 공용 논리 참조)';
COMMENT ON COLUMN wms.inventory_history.line_no              IS '참조 주문 라인 순번 (선택). INIT는 NULL';
COMMENT ON COLUMN wms.inventory_history.changed_by           IS '재고 반영 수행자';
COMMENT ON COLUMN wms.inventory_history.changed_at           IS '재고 반영 일시';
COMMENT ON COLUMN wms.inventory_history.created_at           IS '등록 일시';
COMMENT ON COLUMN wms.inventory_history.updated_at           IS '수정 일시';
COMMENT ON COLUMN wms.inventory_history.created_by           IS '등록자';
COMMENT ON COLUMN wms.inventory_history.updated_by           IS '수정자';

-- -----------------------------------------------------------------------------
-- 3. 공통코드 INV_TXN_TYPE
-- -----------------------------------------------------------------------------
INSERT INTO wms.code_group (group_code, group_name, is_active, created_by, updated_by)
VALUES ('INV_TXN_TYPE', '재고 거래 유형', TRUE, 'seed', 'seed')
ON CONFLICT (group_code) DO UPDATE
SET group_name = EXCLUDED.group_name,
    is_active  = EXCLUDED.is_active,
    updated_at = now(),
    updated_by = 'seed';

INSERT INTO wms.common_code (code_group_id, code_value, code_name, sort_order, is_active, created_by, updated_by)
SELECT cg.code_group_id, v.code_value, v.code_name, v.sort_order, TRUE, 'seed', 'seed'
FROM wms.code_group cg
CROSS JOIN (VALUES
    ('INBOUND',  '입고 반영', 1),
    ('OUTBOUND', '출고 반영', 2),
    ('INIT',     '초기재고',  3)
) AS v(code_value, code_name, sort_order)
WHERE cg.group_code = 'INV_TXN_TYPE'
ON CONFLICT (code_group_id, code_value) DO UPDATE
SET code_name  = EXCLUDED.code_name,
    sort_order = EXCLUDED.sort_order,
    is_active  = EXCLUDED.is_active,
    updated_at = now(),
    updated_by = 'seed';

-- -----------------------------------------------------------------------------
-- 4. 초기 재고 1000 + INIT 이력 (활성 센터 × 활성 품목)
--     재실행: 잔량·INIT 이력은 이미 있으면 건너뜀 (운영 수량 덮어쓰지 않음)
-- -----------------------------------------------------------------------------
INSERT INTO wms.inventory_balance (
    center_info_id, item_info_id, qty_on_hand, created_by, updated_by
)
SELECT c.center_info_id, i.item_info_id, 1000, 'seed', 'seed'
FROM wms.center_info c
CROSS JOIN wms.item_info i
WHERE c.is_active = TRUE
  AND i.is_active = TRUE
ON CONFLICT (center_info_id, item_info_id) DO NOTHING;

INSERT INTO wms.inventory_history (
    inventory_balance_id, txn_type_code, change_qty, after_qty,
    order_kind, order_no, line_no, changed_by, changed_at, created_by, updated_by
)
SELECT b.inventory_balance_id, 'INIT', 1000, b.qty_on_hand,
       NULL, NULL, NULL, 'seed', now(), 'seed', 'seed'
FROM wms.inventory_balance b
JOIN wms.center_info c ON c.center_info_id = b.center_info_id
JOIN wms.item_info i ON i.item_info_id = b.item_info_id
WHERE c.is_active = TRUE
  AND i.is_active = TRUE
  AND NOT EXISTS (
      SELECT 1
      FROM wms.inventory_history h
      WHERE h.inventory_balance_id = b.inventory_balance_id
        AND h.txn_type_code = 'INIT'
  );

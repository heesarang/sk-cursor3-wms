-- -----------------------------------------------------------------------------
-- 9. status_transition_rule (상태 전이 규칙)
-- -----------------------------------------------------------------------------
CREATE TABLE wms.status_transition_rule (
    status_transition_rule_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_kind                 VARCHAR(20) NOT NULL,
    from_status_code           VARCHAR(10) NOT NULL,
    to_status_code             VARCHAR(10) NOT NULL,
    is_active                  BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by                 VARCHAR(50) NOT NULL,
    updated_by                 VARCHAR(50) NOT NULL,
    CONSTRAINT status_transition_rule_pk PRIMARY KEY (status_transition_rule_id),
    CONSTRAINT status_transition_rule_ux1 UNIQUE (order_kind, from_status_code, to_status_code)
);

COMMENT ON TABLE  wms.status_transition_rule                           IS '주문 상태 전이 허용 규칙';
COMMENT ON COLUMN wms.status_transition_rule.status_transition_rule_id IS '상태 전이 규칙 대리키';
COMMENT ON COLUMN wms.status_transition_rule.order_kind                IS '주문 종류 (코드그룹: ORDER_KIND, 예: INBOUND, OUTBOUND)';
COMMENT ON COLUMN wms.status_transition_rule.from_status_code          IS '출발 상태 코드 (코드그룹: INB_STATUS 또는 OUT_STATUS — order_kind에 따름, 예: 00, 10, 20)';
COMMENT ON COLUMN wms.status_transition_rule.to_status_code            IS '도착 상태 코드 (코드그룹: INB_STATUS 또는 OUT_STATUS — order_kind에 따름, 예: 10, 20, 90)';
COMMENT ON COLUMN wms.status_transition_rule.is_active                 IS '규칙 활성 여부';
COMMENT ON COLUMN wms.status_transition_rule.created_at                IS '등록 일시';
COMMENT ON COLUMN wms.status_transition_rule.updated_at                IS '수정 일시';
COMMENT ON COLUMN wms.status_transition_rule.created_by                IS '등록자';
COMMENT ON COLUMN wms.status_transition_rule.updated_by                IS '수정자';

-- -----------------------------------------------------------------------------
-- 10. order_status_history (주문 상태 이력)
-- -----------------------------------------------------------------------------
CREATE TABLE wms.order_status_history (
    order_status_history_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_kind               VARCHAR(20)  NOT NULL,
    order_no                 VARCHAR(50)  NOT NULL,
    from_status_code         VARCHAR(10)  NOT NULL,
    to_status_code           VARCHAR(10)  NOT NULL,
    changed_by               VARCHAR(50)  NOT NULL,
    change_reason            VARCHAR(500),
    changed_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by               VARCHAR(50)  NOT NULL,
    updated_by               VARCHAR(50)  NOT NULL,
    CONSTRAINT order_status_history_pk PRIMARY KEY (order_status_history_id)
);

CREATE INDEX order_status_history_ix1 ON wms.order_status_history (order_kind, order_no, changed_at);
CREATE INDEX order_status_history_ix2 ON wms.order_status_history (changed_at);

COMMENT ON TABLE  wms.order_status_history                         IS '입·출고 주문 상태 변경 이력 (공용)';
COMMENT ON COLUMN wms.order_status_history.order_status_history_id IS '상태 이력 대리키';
COMMENT ON COLUMN wms.order_status_history.order_kind              IS '주문 종류 (코드그룹: ORDER_KIND, 예: INBOUND, OUTBOUND)';
COMMENT ON COLUMN wms.order_status_history.order_no                IS '주문번호 (물리 FK 없음: 한 이력이 입고·출고 두 부모 중 하나를 가리키므로 단일 부모 FK로 표현 불가. order_kind+order_no로 논리 참조하며 앱이 존재 주문에만 INSERT)';
COMMENT ON COLUMN wms.order_status_history.from_status_code        IS '이전 상태 코드 (코드그룹: INB_STATUS 또는 OUT_STATUS — order_kind에 따름, 예: 00, 10, 20)';
COMMENT ON COLUMN wms.order_status_history.to_status_code          IS '이후 상태 코드 (코드그룹: INB_STATUS 또는 OUT_STATUS — order_kind에 따름, 예: 10, 20, 90)';
COMMENT ON COLUMN wms.order_status_history.changed_by              IS '상태 변경 수행자 (최대 50자)';
COMMENT ON COLUMN wms.order_status_history.change_reason           IS '변경 사유 (선택, 최대 500자)';
COMMENT ON COLUMN wms.order_status_history.changed_at              IS '상태 변경 일시';
COMMENT ON COLUMN wms.order_status_history.created_at              IS '등록 일시';
COMMENT ON COLUMN wms.order_status_history.updated_at              IS '수정 일시';
COMMENT ON COLUMN wms.order_status_history.created_by              IS '등록자';
COMMENT ON COLUMN wms.order_status_history.updated_by              IS '수정자';

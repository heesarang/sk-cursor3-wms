CREATE SCHEMA IF NOT EXISTS wms;

-- -----------------------------------------------------------------------------
-- 1. center_info (센터 기준정보)
-- -----------------------------------------------------------------------------
CREATE TABLE wms.center_info (
    center_info_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    center_no       VARCHAR(50)  NOT NULL,
    center_name     VARCHAR(100) NOT NULL,
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      VARCHAR(50)  NOT NULL,
    updated_by      VARCHAR(50)  NOT NULL,
    CONSTRAINT center_info_pk PRIMARY KEY (center_info_id),
    CONSTRAINT center_info_ux1 UNIQUE (center_no)
);

COMMENT ON TABLE  wms.center_info                IS '센터 기준정보';
COMMENT ON COLUMN wms.center_info.center_info_id IS '센터 대리키';
COMMENT ON COLUMN wms.center_info.center_no      IS '센터 번호 (업무 식별자, 예: CTR01)';
COMMENT ON COLUMN wms.center_info.center_name    IS '센터명';
COMMENT ON COLUMN wms.center_info.is_active      IS '사용 여부 (FALSE=비활성, 물리 삭제 대신 사용)';
COMMENT ON COLUMN wms.center_info.created_at     IS '등록 일시';
COMMENT ON COLUMN wms.center_info.updated_at     IS '수정 일시';
COMMENT ON COLUMN wms.center_info.created_by     IS '등록자';
COMMENT ON COLUMN wms.center_info.updated_by     IS '수정자';

-- -----------------------------------------------------------------------------
-- 2. item_info (상품 기준정보)
-- -----------------------------------------------------------------------------
CREATE TABLE wms.item_info (
    item_info_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sku_no        VARCHAR(50)  NOT NULL,
    item_name     VARCHAR(200) NOT NULL,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by    VARCHAR(50)  NOT NULL,
    updated_by    VARCHAR(50)  NOT NULL,
    CONSTRAINT item_info_pk PRIMARY KEY (item_info_id),
    CONSTRAINT item_info_ux1 UNIQUE (sku_no)
);

COMMENT ON TABLE  wms.item_info              IS '상품 기준정보';
COMMENT ON COLUMN wms.item_info.item_info_id IS '상품 대리키';
COMMENT ON COLUMN wms.item_info.sku_no       IS 'SKU 번호 (업무 식별자, 예: SKU-AAA)';
COMMENT ON COLUMN wms.item_info.item_name    IS '품목명';
COMMENT ON COLUMN wms.item_info.is_active    IS '사용 여부 (FALSE=비활성, 물리 삭제 대신 사용)';
COMMENT ON COLUMN wms.item_info.created_at   IS '등록 일시';
COMMENT ON COLUMN wms.item_info.updated_at   IS '수정 일시';
COMMENT ON COLUMN wms.item_info.created_by   IS '등록자';
COMMENT ON COLUMN wms.item_info.updated_by   IS '수정자';

-- -----------------------------------------------------------------------------
-- 3. code_group (공통코드 그룹)
-- -----------------------------------------------------------------------------
CREATE TABLE wms.code_group (
    code_group_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    group_code     VARCHAR(30)  NOT NULL,
    group_name     VARCHAR(100) NOT NULL,
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by     VARCHAR(50)  NOT NULL,
    updated_by     VARCHAR(50)  NOT NULL,
    CONSTRAINT code_group_pk PRIMARY KEY (code_group_id),
    CONSTRAINT code_group_ux1 UNIQUE (group_code)
);

COMMENT ON TABLE  wms.code_group               IS '공통코드 그룹';
COMMENT ON COLUMN wms.code_group.code_group_id IS '코드그룹 대리키';
COMMENT ON COLUMN wms.code_group.group_code    IS '그룹 코드 (업무 식별자, 예: INB_STATUS, OUT_STATUS, ORDER_KIND)';
COMMENT ON COLUMN wms.code_group.group_name    IS '그룹명';
COMMENT ON COLUMN wms.code_group.is_active     IS '사용 여부';
COMMENT ON COLUMN wms.code_group.created_at    IS '등록 일시';
COMMENT ON COLUMN wms.code_group.updated_at    IS '수정 일시';
COMMENT ON COLUMN wms.code_group.created_by    IS '등록자';
COMMENT ON COLUMN wms.code_group.updated_by    IS '수정자';

-- -----------------------------------------------------------------------------
-- 4. common_code (공통코드)
-- -----------------------------------------------------------------------------
CREATE TABLE wms.common_code (
    common_code_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code_group_id   BIGINT       NOT NULL,
    code_value      VARCHAR(30)  NOT NULL,
    code_name       VARCHAR(100) NOT NULL,
    sort_order      INT          NOT NULL DEFAULT 0,
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      VARCHAR(50)  NOT NULL,
    updated_by      VARCHAR(50)  NOT NULL,
    CONSTRAINT common_code_pk PRIMARY KEY (common_code_id),
    CONSTRAINT common_code_ux1 UNIQUE (code_group_id, code_value),
    CONSTRAINT common_code_code_group_fk FOREIGN KEY (code_group_id)
        REFERENCES wms.code_group (code_group_id)
);

COMMENT ON TABLE  wms.common_code                IS '공통코드';
COMMENT ON COLUMN wms.common_code.common_code_id IS '공통코드 대리키';
COMMENT ON COLUMN wms.common_code.code_group_id  IS '소속 코드그룹 대리키 (FK → code_group)';
COMMENT ON COLUMN wms.common_code.code_value     IS '코드 값 (그룹 내 업무 식별자, 예: 00, 10, INBOUND)';
COMMENT ON COLUMN wms.common_code.code_name      IS '코드 표시명';
COMMENT ON COLUMN wms.common_code.sort_order     IS '그룹 내 표시 순서';
COMMENT ON COLUMN wms.common_code.is_active      IS '사용 여부';
COMMENT ON COLUMN wms.common_code.created_at     IS '등록 일시';
COMMENT ON COLUMN wms.common_code.updated_at     IS '수정 일시';
COMMENT ON COLUMN wms.common_code.created_by     IS '등록자';
COMMENT ON COLUMN wms.common_code.updated_by     IS '수정자';

-- -----------------------------------------------------------------------------
-- 5. inbound_order (입고 주문)
-- -----------------------------------------------------------------------------
CREATE TABLE wms.inbound_order (
    inbound_order_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_no          VARCHAR(50) NOT NULL,
    center_info_id    BIGINT      NOT NULL,
    status_code       VARCHAR(10) NOT NULL,
    ordered_at        TIMESTAMPTZ NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by        VARCHAR(50) NOT NULL,
    updated_by        VARCHAR(50) NOT NULL,
    CONSTRAINT inbound_order_pk PRIMARY KEY (inbound_order_id),
    CONSTRAINT inbound_order_ux1 UNIQUE (order_no),
    CONSTRAINT inbound_order_center_info_fk FOREIGN KEY (center_info_id)
        REFERENCES wms.center_info (center_info_id)
);

CREATE INDEX inbound_order_ix1 ON wms.inbound_order (center_info_id, status_code);

COMMENT ON TABLE  wms.inbound_order                  IS '입고 주문 헤더';
COMMENT ON COLUMN wms.inbound_order.inbound_order_id IS '입고 주문 대리키';
COMMENT ON COLUMN wms.inbound_order.order_no         IS '입고 주문번호 (업무 식별자, 예: IB-CTR01-001)';
COMMENT ON COLUMN wms.inbound_order.center_info_id   IS '처리 센터 대리키 (FK → center_info)';
COMMENT ON COLUMN wms.inbound_order.status_code      IS '입고 상태 코드 (코드그룹: INB_STATUS, 예: 00 주문생성, 10 검수중, 20 검수완료, 90 입고확정). 공통코드 논리 참조(물리 FK 없음)';
COMMENT ON COLUMN wms.inbound_order.ordered_at       IS '주문 일시';
COMMENT ON COLUMN wms.inbound_order.created_at       IS '등록 일시';
COMMENT ON COLUMN wms.inbound_order.updated_at       IS '수정 일시';
COMMENT ON COLUMN wms.inbound_order.created_by       IS '등록자';
COMMENT ON COLUMN wms.inbound_order.updated_by       IS '수정자';

-- -----------------------------------------------------------------------------
-- 6. inbound_order_line (입고 주문 라인)
-- -----------------------------------------------------------------------------
CREATE TABLE wms.inbound_order_line (
    inbound_order_line_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    inbound_order_id       BIGINT        NOT NULL,
    line_no                INT           NOT NULL,
    item_info_id           BIGINT        NOT NULL,
    order_qty              NUMERIC(12,0) NOT NULL,
    inspected_qty          NUMERIC(12,0) NOT NULL DEFAULT 0,
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by             VARCHAR(50)   NOT NULL,
    updated_by             VARCHAR(50)   NOT NULL,
    CONSTRAINT inbound_order_line_pk PRIMARY KEY (inbound_order_line_id),
    CONSTRAINT inbound_order_line_ux1 UNIQUE (inbound_order_id, line_no),
    CONSTRAINT inbound_order_line_inbound_order_fk FOREIGN KEY (inbound_order_id)
        REFERENCES wms.inbound_order (inbound_order_id),
    CONSTRAINT inbound_order_line_item_info_fk FOREIGN KEY (item_info_id)
        REFERENCES wms.item_info (item_info_id),
    CONSTRAINT inbound_order_line_ck1 CHECK (order_qty >= 0),
    CONSTRAINT inbound_order_line_ck2 CHECK (inspected_qty >= 0),
    CONSTRAINT inbound_order_line_ck3 CHECK (inspected_qty <= order_qty)
);

CREATE INDEX inbound_order_line_ix1 ON wms.inbound_order_line (item_info_id);

COMMENT ON TABLE  wms.inbound_order_line                       IS '입고 주문 라인';
COMMENT ON COLUMN wms.inbound_order_line.inbound_order_line_id IS '입고 주문 라인 대리키';
COMMENT ON COLUMN wms.inbound_order_line.inbound_order_id      IS '소속 입고 주문 대리키 (FK → inbound_order)';
COMMENT ON COLUMN wms.inbound_order_line.line_no               IS '라인 순번 (주문 내 업무 식별자)';
COMMENT ON COLUMN wms.inbound_order_line.item_info_id          IS '상품 대리키 (FK → item_info). 동일 주문 내 SKU 중복 허용';
COMMENT ON COLUMN wms.inbound_order_line.order_qty             IS '주문 수량 (≥ 0)';
COMMENT ON COLUMN wms.inbound_order_line.inspected_qty         IS '검수 확정 수량 (≥ 0, ≤ order_qty). F1~F4에서는 시드·조회 전용';
COMMENT ON COLUMN wms.inbound_order_line.created_at            IS '등록 일시';
COMMENT ON COLUMN wms.inbound_order_line.updated_at            IS '수정 일시';
COMMENT ON COLUMN wms.inbound_order_line.created_by            IS '등록자';
COMMENT ON COLUMN wms.inbound_order_line.updated_by            IS '수정자';

